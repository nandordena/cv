 function getWorkTime(a){
   if(a.dateEnd == 'no') return 0;
   return parseInt(
         (a.dateEnd?new Date(a.dateEnd):new Date()) 
         - (new Date(a.date)).getTime()
     );
 }
 function chageSection(e){
   let sec = e.getAttribute("data-section");
   document.body.setAttribute("data-section-status",sec);
 }
 function getYearsOfTime(t){
   return (new Date(t)).toLocaleDateString({},{year:'numeric'}) - 1970;
 }
 function getMontsRestOfTime(t){
   let y = getYearsOfTime(t);
   return parseInt(
     ( t / (1000 * 3600 * 24 * 30.44) ) - (12*y)
   );
 }
 function copyToClipboard(str){
   const el = document.createElement('textarea');
   el.value = str;
   el.setAttribute('readonly', '');
   el.style.position = 'absolute';
   el.style.left = '-9999px';
   document.body.appendChild(el);
   const selected =
     document.getSelection().rangeCount > 0?
     document.getSelection().getRangeAt(0) : false;
   el.select();
   document.execCommand('copy');
   document.body.removeChild(el);
   if (selected) {
     document.getSelection().removeAllRanges();
     document.getSelection().addRange(selected);
   }
 };
 function clickToCopy(ele){
   text = ele.getAttribute('text-copy');
   copyToClipboard(text);
   ele.classList.add('copyed');
   setTimeout(function() {
     ele.classList.remove('copyed');
   }, 1000);
 }
 
